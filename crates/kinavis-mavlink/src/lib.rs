//! MAVLink 2 for the KINAVIS crates: frames, checksums and signatures, and
//! the messages a ground vehicle on ArduPilot (Rover) exchanges.
//!
//! MAVLink is the protocol of ArduPilot and PX4 autopilots: frames of a
//! header, a payload of little-endian fields and a checksum seeded per
//! message (`CRC_EXTRA`), optionally signed. This crate reads and writes
//! them without an allocator:
//!
//! 1. **Frames**: [`Deframer`] takes a byte stream (serial, UDP) and yields
//!    [`Frame`]s with their checksum checked, MAVLink 2 or 1; [`Frame::new`]
//!    and [`Frame::encode`] write MAVLink 2, trailing zeros dropped.
//! 2. **Messages**: generated by `cargo xtask mavlink` from ArduPilot's
//!    dialect; see [`Message`].
//! 3. **Kernel types**: positions, heights with their datum, NED velocities,
//!    attitude, GNSS fixes; commands from positions. Units and the datum of
//!    height only: MAVLink is NED like the kernel, and a height above sea
//!    level stays one until converted with a geoid model.
//! 4. **Signing** *(feature `signing`)*: SHA-256 signatures, sign and verify;
//!    SHA-256 is this crate's own, checked against the FIPS 180-4 vectors.
//!
//! ```rust
//! use kinavis_mavlink::{Deframer, Frame, GlobalPositionInt, Message};
//!
//! // Position of system 1, as an autopilot sends it.
//! let sent = GlobalPositionInt { lat: 515_000_000, lon: -1_200_000, alt: 54_300, hdg: 9_000, ..GlobalPositionInt::ZERO };
//! let mut bytes = [0u8; kinavis_mavlink::MAX_FRAME];
//! let len = Frame::new(1, 1, 0, &Message::GlobalPositionInt(sent)).encode(&mut bytes);
//!
//! let mut deframer = Deframer::new();
//! let frame = bytes[..len].iter().find_map(|&byte| deframer.push(byte)).unwrap()?;
//! let Some(Message::GlobalPositionInt(position)) = frame.message() else { panic!() };
//! assert_eq!(format!("{:.4}", position.point()?.position()), "51°30.0000'N 000°07.2000'W");
//! assert_eq!(position.heading().map(|h| h.degrees()), Some(90.0));
//! # Ok::<(), Box<dyn std::error::Error>>(())
//! ```
//!
//! # Feature flags
//!
//! - `std` *(default)* — standard library maths in the kernel.
//! - `libm` — for `no_std` targets: `--no-default-features --features libm`.
//! - `signing` — message signatures.
//!
//! No allocation, no panics on any input.

